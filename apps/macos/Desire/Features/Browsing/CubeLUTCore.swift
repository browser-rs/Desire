import Foundation

/// .cube LUT 解析/生成（迭代 2 · v0.8.42）：最小 3D LUT 读写。
/// 解析只支持 `LUT_3D_SIZE N` + N³ 行 RGB float（标准 .cube 格式子集）；
/// 生成按 32³ 输出（足夠调节精度）。
nonisolated enum CubeLUTCore {

    struct Parsed: Equatable {
        var title: String?
        var dimension: Int
        /// N³ × 3 个 float（0…1）
        var data: [Float]
    }

    // MARK: - 解析

    static func parse(_ text: String) -> Parsed? {
        var dimension = 0
        var title: String?
        var values: [Float] = []
        for rawLine in text.split(separator: "\n") {
            let line = rawLine.trimmingCharacters(in: .whitespaces)
            if line.isEmpty || line.hasPrefix("#") { continue }
            if line.hasPrefix("TITLE") {
                title = line.dropFirst(5).trimmingCharacters(in: .whitespaces)
                    .trimmingCharacters(in: CharacterSet(charactersIn: "\""))
                continue
            }
            if line.hasPrefix("LUT_3D_SIZE") {
                dimension = Int(line.dropFirst(11).trimmingCharacters(in: .whitespaces)) ?? 0
                continue
            }
            if line.hasPrefix("LUT_1D_SIZE") || line.hasPrefix("DOMAIN_") {
                continue
            }
            let parts = line.split(separator: " ")
            guard parts.count == 3,
                  let r = Float(parts[0]), let g = Float(parts[1]), let b = Float(parts[2])
            else { continue }
            values.append(r)
            values.append(g)
            values.append(b)
        }
        guard dimension >= 2, dimension <= 64,
              values.count == dimension * dimension * dimension * 3 else {
            return nil
        }
        return Parsed(title: title, dimension: dimension, data: values)
    }

    // MARK: - 生成

    /// 从当前调节参数生成 .cube 文本（32³；与渲染器的 channel LUT 同逻辑）。
    static func generate(_ params: ImageAdjustParams, title: String,
                         dimension: Int = 32) -> String {
        let d = max(2, min(64, dimension))
        var lines: [String] = []
        lines.append("# Generated by Desire Image Editor")
        lines.append("TITLE \"\(title.replacingOccurrences(of: "\"", with: "'"))\"")
        lines.append("LUT_3D_SIZE \(d)")
        for b in 0..<d {
            let blue = Double(b) / Double(d - 1)
            for g in 0..<d {
                let green = Double(g) / Double(d - 1)
                for r in 0..<d {
                    let red = Double(r) / Double(d - 1)
                    let out = applyParamsToRGB(params, r: red, g: green, b: blue)
                    lines.append(String(format: "%.6f %.6f %.6f",
                                        out.0, out.1, out.2))
                }
            }
        }
        return lines.joined(separator: "\n") + "\n"
    }

    /// 与 ImagePipelineRenderer 相同语义的简化 CPU 映射（曲线 + 色阶 + 色彩控制）。
    static func applyParamsToRGB(
        _ params: ImageAdjustParams, r: Double, g: Double, b: Double
    ) -> (Double, Double, Double) {
        // 色阶
        let span = max(0.000_001, params.whitePoint - params.blackPoint)
        func levels(_ value: Double) -> Double {
            (value - params.blackPoint) / span
        }
        var out = (levels(r), levels(g), levels(b))

        // RGB 曲线
        if params.hasCurve {
            out.0 = ImageAdjustParams.curveValue(params.curvePoints, at: out.0)
            out.1 = ImageAdjustParams.curveValue(params.curvePoints, at: out.1)
            out.2 = ImageAdjustParams.curveValue(params.curvePoints, at: out.2)
        }
        if params.hasChannelCurves {
            out.0 = ImageAdjustParams.curveValue(params.curveRed, at: out.0)
            out.1 = ImageAdjustParams.curveValue(params.curveGreen, at: out.1)
            out.2 = ImageAdjustParams.curveValue(params.curveBlue, at: out.2)
        }

        // 亮度/对比度（与 CIColorControls 近似语义）
        let brightened = (out.0 - 0.5) * params.contrast + 0.5 + params.brightness
        let contrasted = (out.1 - 0.5) * params.contrast + 0.5 + params.brightness
        let contrastedB = (out.2 - 0.5) * params.contrast + 0.5 + params.brightness
        out = (brightened, contrasted, contrastedB)

        // 饱和度（亮度加权）
        let luma = 0.299 * out.0 + 0.587 * out.1 + 0.114 * out.2
        let saturatedR = luma + (out.0 - luma) * params.saturation
        let saturatedG = luma + (out.1 - luma) * params.saturation
        let saturatedB = luma + (out.2 - luma) * params.saturation
        out = (saturatedR, saturatedG, saturatedB)

        return (out.0.clamped(0, 1), out.1.clamped(0, 1), out.2.clamped(0, 1))
    }
}
